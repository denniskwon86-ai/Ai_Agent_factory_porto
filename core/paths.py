"""[D-018 후속 1] 저장소 경로의 **단일 기준점**.

## 왜 필요한가 — 상대경로가 실행 디렉터리에 따라 다른 파일을 열었다

`os.path.join("data", "enterprise_context.db")` 같은 상대경로는 **프로세스의 현재 작업
디렉터리**를 기준으로 해석된다. 그래서 같은 코드가 어디서 실행됐는지에 따라 다른 파일을 연다:

  · 프로젝트 루트에서 기동 → `<root>/data/enterprise_context.db` (의도한 파일)
  · 다른 디렉터리에서 기동 → `<그곳>/data/enterprise_context.db` — **없으면 빈 DB 를 새로 만든다**

⚠️⚠️ 조직 그래프에서 이것이 특히 위험하다. 빈 DB 가 열리면 노드가 0 건이고, 범위 해석은
  fail-closed 이므로 **모든 사용자가 아무것도 못 보는 상태**가 된다. 그런데 오류는 어디에도
  나지 않는다 — «권한이 없다» 로 보이고, 원인을 찾으려면 cwd 를 의심해야 한다.
  실측(2026-08-05): pytest 안에서 `resolve_scope_ref` 가 `LS_MNM`·`MNM_BATTERY` 를 모두 빈
  값으로 돌려줬다. 정본 불일치로 보였으나 실제 원인은 **다른 DB 파일을 열고 있었던 것**이다.
  진단이 한 단계 엉뚱한 곳을 향했고, 그 사이 «범위 정본이 깨졌다» 는 잘못된 결론을 냈다.

## 기준점을 `__file__` 로 잡은 이유

작업 공간마다 자기 데이터를 갖는다(워크트리에도 별도 `data/` 가 있다). 그래서 «프로세스가
어디서 떴는가» 가 아니라 **«이 코드가 어느 저장소에 속하는가»** 를 기준으로 삼는다. 그러면
워크트리에서 돌린 코드는 워크트리 데이터를, 메인에서 돌린 코드는 메인 데이터를 쓴다 —
디렉터리를 옮겨 실행해도 같은 파일을 본다.

## 테스트 격리와의 관계

여기서 정하는 것은 **기본값**뿐이다. 테스트는 `tests/conftest.py` 가 인스턴스의 `db_path` 를
tmp 로 갈아끼워 격리한다(그 격리는 의도된 것이다 — 조직도가 있는 환경과 없는 환경에서 같은
테스트가 다른 결과를 내던 실측 때문이다). 절대경로 고정은 그 격리를 깨지 않는다: 격리는
기본값을 **덮어쓰는** 방식이고, 기본값이 정확해질 뿐이다.
"""
import os

#: 이 저장소의 루트(= `core/` 의 부모). 환경 변수로 덮을 수 있게 두지 않는다 —
#: 덮을 수 있으면 «어느 데이터를 보고 있는가» 가 다시 실행 환경에 좌우된다.
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

#: 런타임 데이터 뿌리. 저장소에 추적되지 않는다(`.gitignore: *.db`).
DATA_DIR = os.path.join(PROJECT_ROOT, "data")


def data_path(*parts: str) -> str:
    """`data/` 아래 경로를 **절대경로**로 만든다.

    ⚠️ 디렉터리를 여기서 만들지 않는다. 저장소마다 «언제 만들 것인가» 가 다르고(읽기 전용
      조회에서 빈 디렉터리를 만들면 «데이터가 있다» 는 오해를 준다), 각 저장소가 자기 시점에
      `makedirs` 를 부른다."""
    return os.path.join(DATA_DIR, *parts)


def project_path(*parts: str) -> str:
    """저장소 루트 기준 절대경로(데이터 이외 — `templates/`·`skills/` 등)."""
    return os.path.join(PROJECT_ROOT, *parts)


#: SW 생성 프로젝트의 작업공간 뿌리. **여기에 사용자 산출물이 들어 있다.**
PROJECTS_DIR = os.path.join(PROJECT_ROOT, "projects")


def workspace_path(*parts: str) -> str:
    """생성 프로젝트 작업공간 경로를 **절대경로**로 만든다.

    ★★★ [2026-08-05 실측 결함] DB 경로는 이 파일로 고정했는데 **작업공간은 `"./projects"` 상대
      경로로 남아 있었다**(35곳). 그래서 서버를 저장소 루트가 아닌 곳에서 띄우면
      `GET /api/v1/factory/projects` 가 **다른 디렉터리를 읽는다.** 실측: 워크트리에서 백엔드를
      기동했더니 프로젝트 목록에 실제 프로젝트 9개 대신 테스트 잔여물 1개만 나왔다.

    ⚠️ 이것은 «목록이 비어 보인다» 로 끝나지 않는다. `os.makedirs(..., exist_ok=True)` 를 하는
      경로들이 있어서 **엉뚱한 위치에 빈 작업공간을 새로 만든다.** 그 뒤 사용자가 프로젝트를
      만들면 산출물이 그쪽에 쌓이고, 원래 위치에서 보면 «사라진» 상태가 된다. DB 에서 빈 파일이
      열리던 것과 같은 유형이고, 이쪽은 **사용자가 만든 산출물**이라 더 아프다.

    ## 테스트 격리 — **이 함수가 유일한 관문이다**

    종전에 테스트들은 `monkeypatch.chdir(tmp_path)` 로 격리했다(`./projects` 가 tmp 아래에
    생기도록). 즉 **제품 코드가 cwd 에 의존한다는 사실을 테스트가 전제**하고 있었고, 절대경로로
    고치자 20건이 깨졌다. 그것은 격리가 잘못됐다는 뜻이 아니라 **격리 지점이 cwd 였다**는 뜻이다.

    그래서 지점을 여기로 옮겼다. 호출부는 `PROJECTS_DIR` 을 값으로 복사하지 않고 이 함수를
    부른다(`from core.paths import PROJECTS_DIR` 로 복사하면 그 순간 값이 고정돼 덮을 수 없다).
    테스트는 다음 한 줄로 격리한다:

        monkeypatch.setattr(core.paths, "PROJECTS_DIR", str(tmp_path / "projects"))

    ⚠️ `chdir` 을 함께 두는 것은 무해하다 — `./library` 처럼 아직 상대경로인 곳이 남아 있다.
    """
    return os.path.join(PROJECTS_DIR, *parts)
