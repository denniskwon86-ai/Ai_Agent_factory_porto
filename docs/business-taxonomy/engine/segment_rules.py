def is_region(name: str) -> bool:
    """지역 세그먼트인가 — 사업 구분이 아니므로 버린다"""
    return bool(지역_패턴.match((name or '').strip()))


def classify_segment(name: str, parent: dict | None = None,
                     affiliates: dict | None = None) -> dict:
    """
    세그먼트 하나를 판정한다.

    name       : 세그먼트명 (예: '석유화학', 'DS부문', '할인점')
    parent     : 모법인의 판정 결과 (ksic_rules.classify 의 반환). 상속에 쓴다.
                 `_법인명` 은 약어 사전에, `_기업집단` 은 계열사 조인에 쓴다
    affiliates : `affiliate_index()` 가 만든 계열사 색인 (없으면 조인을 건너뛴다)
    """
    nm = (name or '').strip()
    p = parent or {}
    out = {'세그먼트': nm, 'A세분류': p.get('A세분류', ''), 'B1주업종': p.get('B1주업종', ''),
           'B1_2단': p.get('B1_2단', ''), '판정근거': ''}

    if not nm:
        out['판정근거'] = '이름 없음'
        return out

    if is_region(nm):
        out.update({'A세분류': '', 'B1주업종': '', 'B1_2단': '', '판정근거': '지역 세그먼트 — 제외'})
        return out

    # 회사 고유 약어를 키워드보다 먼저 본다
    abbr, val = _abbrev(p.get('_법인명', ''), nm)
    if val:
        a, b, t = val
        out.update({'A세분류': a or out['A세분류'], 'B1주업종': b, 'B1_2단': t,
                    '판정근거': f'약어 「{abbr}」'})
        return out

    key = nm.replace(' ', '').replace('부문', '').replace('사업', '').upper()
    key = re.sub(r'(및)?기타$', '', key) or key      # 「PI 및 기타」의 꼬리를 뗀다

    if key in EXACT:
        a, b, t = EXACT[key]
        out.update({'A세분류': a or out['A세분류'], 'B1주업종': b, 'B1_2단': t,
                    '판정근거': f'약어 「{key}」'})
        return out

    for kw, (a, b, t) in KEYWORDS:
        if kw.upper() in key:
            out['B1주업종'] = b
            out['B1_2단'] = t
            if a:
                out['A세분류'] = a
            out['판정근거'] = f'키워드 「{kw}」' + ('' if a else ' (A 는 모법인 상속)')
            return out

    # 이름으로 판정이 안 되면 **계열사 조인**을 본다. 순수 지주회사의 부문은
    # 계열사명이라 키워드가 걸리지 않는다. 이름 판정을 먼저 두는 이유는,
    # 계열사 조인이 신고 KSIC 에 의존해서다 — SKC 는 지주회사로 신고했지만
    # 실제 사업은 화학·소재다. 키워드가 잡을 수 있으면 그게 더 정확하다
    hit, val = _affiliate(p.get('_기업집단', ''), nm, affiliates or {})
    if val:
        a, b, t = val
        out.update({'A세분류': a or out['A세분류'], 'B1주업종': b, 'B1_2단': t,
                    '판정근거': f'계열사 「{hit}」'})
        return out

    out['판정근거'] = '상속 — 키워드 없음'
    return out


def split_instances(parent_name: str, parent_result: dict, segments: list[dict]) -> list[dict]:
    """
    법인 1건을 세그먼트 n 건으로 나눈다.

    segments: [{'명칭': '석유화학', '매출': 12345}, ...]
    세그먼트가 없거나 전부 지역이면 법인 1건을 그대로 돌려준다.
    """
    usable = [s for s in segments if not is_region(s.get('명칭', ''))]
    if not usable:
        return [{**parent_result, '인스턴스명': parent_name, '담김형태': '법인형',
                 '식별근거등급': parent_result.get('식별근거등급', '공시법인')}]

    out = []
    ctx = {**parent_result, '_법인명': parent_name}
    for s in usable:
        r = classify_segment(s.get('명칭', ''), ctx)
        out.append({
            '인스턴스명': f"{parent_name} / {s.get('명칭', '')}",
            '모법인': parent_name,
            '담김형태': '부문형',
            '식별근거등급': '공시부문',
            'A세분류': r['A세분류'], 'B1주업종': r['B1주업종'], 'B1_2단': r['B1_2단'],
            '매출액': s.get('매출', ''),
            '판정근거': r['판정근거'],
        })
    return out


