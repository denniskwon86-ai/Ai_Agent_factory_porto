def _lookup_ksic(ksic: str) -> tuple[str, ...]:
    ksic = (ksic or '').strip().upper()
    if not ksic:
        return ()
    for n in (6, 5, 4, 3):
        hit = KSIC_VC.get(ksic[:n])
        if hit:
            return hit
    return ()


def classify(ksic: str = '', name: str = '', seg_name: str = '', b2: str = '') -> dict:
    """
    밸류체인을 판정한다 — 복수값, 첫 값이 주 밸류체인.

    ksic     : 법인의 KSIC (자기 업종이 곧 생태계인 경우)
    name     : 회사명 (소재·장비사를 잡는 키워드)
    seg_name : 부문명 (있으면 회사명보다 구체적이다)
    b2       : B축 2단 — 이미 판정된 품목. 이름에 단서가 없어도 잡는다

    돌려주는 것: {'밸류체인': ('이차전지', ...), '판정근거': '...'}
    """
    got: list[str] = []
    why: list[str] = []

    def add(vcs, src):
        for v in vcs:
            if v not in got:
                got.append(v)
                why.append(src)

    # ① 이름·부문명 키워드 — 소재·장비사는 이쪽만 잡는다. 부문명이 더 구체적이라 먼저
    text = _법인표기.sub('', f'{seg_name} {name}').upper()
    for kw, vcs in KEYWORDS:
        if kw.upper() in text:
            add(vcs, f'이름 「{kw}」')
            break                      # 첫(가장 긴) 키워드만 — 여럿 붙이면 오탐이 늘어난다

    # ② B축 2단 — KSIC 보다 정확하다(이미 부문명까지 반영된 판정이다)
    if b2 and b2 in B2_VC:
        add(B2_VC[b2], f'B축 2단 「{b2}」')

    # ③ KSIC — 자기 업종이 곧 생태계인 경우
    add(_lookup_ksic(ksic), f'KSIC {ksic}')

    return {'밸류체인': tuple(got), '판정근거': ' · '.join(why)}


def stage(a_sub: str) -> int | None:
    """A세분류 → 가치사슬 단계 순번. 서비스·유통·금융은 단계가 아니라 None"""
    return A_STAGE.get(a_sub)


