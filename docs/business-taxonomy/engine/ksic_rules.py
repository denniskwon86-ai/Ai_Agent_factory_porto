# 묶음 노드로 판정할 KSIC — 그 매출이 모수 안 다른 인스턴스 매출을 포함한다
묶음_KSIC = ('K6499', 'M7151')


def _lookup(ksic: str):
    """긴 접두사부터 찾는다: 5 → 4 → 3 → 1자리"""
    if not ksic:
        return None
    for n in (5, 4, 3, 1):
        hit = MAP.get(ksic[:n])
        if hit:
            return hit
    return None


def classify(ksic: str, sales, name: str = '', employees=None) -> dict:
    """
    한 법인을 판정한다.

    sales     : 매출액(백만원). 0 이면 모수 밖
    employees : 종업원수(선택). 판정에는 쓰지 않고 근거로만 남긴다
    """
    def num(v):
        if v in (None, ''):
            return None
        return int(str(v).replace(',', '').replace(' ', '') or 0)

    s = num(sales)
    ksic = (ksic or '').strip().upper()
    out = {'KSIC': ksic, 'A세분류': '', 'A대분류': '', 'B1주업종': '', 'B1_2단': '',
           '묶음노드': '', '모수계층': '', '판정근거': ''}

    # ① 매출 0 → 모수 밖 (사업 실질이 없는 껍데기)
    if s == 0:
        out['모수계층'] = '모수밖'
        out['판정근거'] = '매출 0'
        return out

    # ② 지주회사 → 묶음 노드
    if ksic[:5] in 묶음_KSIC:
        a, b, t = MAP[ksic[:5]]
        out.update({'A세분류': a, 'B1주업종': b, 'B1_2단': t, '묶음노드': 'Y',
                    'A대분류': A_대분류[a], '모수계층': 'T2',
                    '판정근거': f'{ksic[:5]} 지주회사'})
        return out

    # ③ KSIC 매핑
    hit = _lookup(ksic)
    if not hit:
        out['모수계층'] = 'T2'
        out['판정근거'] = f'미판정 — KSIC {ksic} 매핑 없음'
        return out

    a, b, t = hit
    out.update({'A세분류': a, 'B1주업종': b, 'B1_2단': t,
                'A대분류': A_대분류[a], '모수계층': 'T2',
                '판정근거': f'KSIC {ksic}'})
    return out


def classify_rows(rows):
    """rows: [{'법인명','KSIC','매출액','종업원수'}, ...] → 판정 결과를 붙여 돌려준다"""
    out = []
    for r in rows:
        res = classify(r.get('KSIC'), r.get('매출액'), r.get('법인명', ''), r.get('종업원수'))
        out.append({**r, **res})
    return out


