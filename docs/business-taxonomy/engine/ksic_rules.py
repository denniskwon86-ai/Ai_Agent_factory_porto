# 묶음 노드로 판정할 KSIC — 그 매출이 모수 안 다른 인스턴스 매출을 포함한다
묶음_KSIC = ('K6499', 'M7151')

# **5 자리 정확일치라 새어 나간 지주회사들.** M715(4 자리) · M7153 · M71531 ·
# K649 · K64919 로 신고한 지주회사가 사업회사로 섰다 — 녹십자홀딩스 · NICE홀딩스 ·
# 대성합동지주 · 심텍홀딩스가 「인적서비스 × 전문서비스」였다. 그러면 자회사와
# 매출이 겹쳐 이중계상된다.
#
# 다만 **KSIC 만으로는 못 가른다**: M7153 은 경영 컨설팅이기도 하다. 그래서
# **이름이 「지주」·「홀딩스」로 끝나는 것과 교집합**으로 좁힌다 — 실측 66 건이
# 전부 실제 지주회사였다. 이름만 홀딩스인 사업회사는 KSIC 가 달라 걸리지 않고
# (원익홀딩스 = C2927 반도체 장비 · 트리밍버드홀딩스 = C1411 의류),
# 「미건에너지주식회사」처럼 「에너지 + 주식회사」인 것도 법인표기를 뗀 뒤 보므로 안전하다
_지주계열 = __import__('re').compile(r'^(K649|M715)')
_지주이름 = __import__('re').compile(r'(지주|홀딩스|HOLDINGS)$', __import__('re').I)
_법인표기 = __import__('re').compile(
    r'㈜|\(주\)|\(유\)|\(합\)|주식회사|유한회사|유한책임회사|합자회사')


def is_holding(ksic: str, name: str) -> bool:
    """묶음 노드(지주회사)인가 — KSIC 정확일치 또는 지주계열 KSIC + 지주 이름"""
    ksic = (ksic or '').strip().upper()
    if ksic[:5] in 묶음_KSIC:
        return True
    return bool(_지주계열.match(ksic)
                and _지주이름.search(_법인표기.sub('', name or '').strip()))


def _four(v):
    """(A, B1, B2) → (A, B1, B2, B3). **3 단은 같은 품목 안의 공정·형태 단계**다 —
    제련→압연→가공, 강관·전선. 셀을 만들지 않는 필터이고, 몰린 곳(금속)만 채운다.
    3 단이 없는 규칙은 빈칸이다"""
    return tuple(v) + ('',) * (4 - len(v))


def _lookup(ksic: str):
    """긴 접두사부터 찾는다: 세세분류(문자+5자리) → 세분류 → 소분류 → 중분류 → 대분류

    키 길이는 **문자를 포함**한다 — 'G47111' 은 6 자다. 5 까지만 보던 탓에 소매
    세세분류 규칙이 하나도 걸리지 않았다(DART 상장사 KSIC 224 건이 6 자였다)"""
    if not ksic:
        return None
    for n in (6, 5, 4, 3, 1):
        hit = MAP.get(ksic[:n])
        if hit:
            return hit
    return None


def classify(ksic: str, sales, name: str = '', employees=None) -> dict:
    """
    한 법인을 판정한다.

    sales     : 매출액(백만원). 0 이면 모수 밖
    employees : 종업원수(선택). 판정에는 쓰지 않고 근거로만 남긴다
    """
    def num(v):
        if v in (None, ''):
            return None
        return int(str(v).replace(',', '').replace(' ', '') or 0)

    s = num(sales)
    ksic = (ksic or '').strip().upper()
    out = {'KSIC': ksic, 'A세분류': '', 'A대분류': '', 'B1주업종': '', 'B1_2단': '', 'B1_3단': '',
           '묶음노드': '', '모수계층': '', '판정근거': ''}

    # ① 매출 0 → 모수 밖 (사업 실질이 없는 껍데기)
    if s == 0:
        out['모수계층'] = '모수밖'
        out['판정근거'] = '매출 0'
        return out
    # ①′ SPAC(기업인수목적회사) → 모수 밖. 상장돼 있어 T1 로 들어오지만 사업이
    # 없는 껍데기다 — 상장 표본 24 건 중 4 건이 「~제N호기업인수목적」이었다.
    # 업무키트를 적용할 조직이 없으므로 롱리스트에 있으면 안 된다
    if '기업인수목적' in (name or ''):
        out['모수계층'] = '모수밖'
        out['판정근거'] = 'SPAC — 기업인수목적회사'
        return out

    # ② 지주회사 → 묶음 노드
    if is_holding(ksic, name):
        a, b, t, t3 = _four(MAP['K6499'])   # 지주·투자 × 다품목·범용
        why = (f'{ksic[:5]} 지주회사' if ksic[:5] in 묶음_KSIC
               else f'KSIC {ksic} + 이름이 지주·홀딩스')
        out.update({'A세분류': a, 'B1주업종': b, 'B1_2단': t, 'B1_3단': t3, '묶음노드': 'Y',
                    'A대분류': A_대분류[a], '모수계층': 'T2', '판정근거': why})
        return out

    # ③ KSIC 매핑
    hit = _lookup(ksic)
    if not hit:
        out['모수계층'] = 'T2'
        out['판정근거'] = f'미판정 — KSIC {ksic} 매핑 없음'
        return out

    a, b, t, t3 = _four(hit)
    why = f'KSIC {ksic}'
    # **종합소매를 4 자리로 신고한 회사는 이름으로 2 단을 보조한다.** 공정위 계열사
    # KSIC 는 4 자리라 G4711(백화점·대형마트)·G4712(슈퍼·편의점)가 갈리지 않는다 —
    # 이마트·롯데마트·BGF리테일이 2 단 없이 남았다. KSIC 가 종합소매일 때만 보므로
    # 「마트」가 든 비소매 회사에는 걸리지 않는다
    if not t and ksic[:5] in ('G4711', 'G4712'):
        nm = name or ''
        for kw, t2 in (('백화점', '백화점'), ('편의점', '편의점'), ('슈퍼', '슈퍼마켓'),
                       ('마트', '대형마트'), ('아울렛', '전문점')):
            if kw in nm:
                t, why = t2, f'KSIC {ksic} + 이름 「{kw}」'
                break
    # **타이어사가 C221(4 자리)로 신고했다.** 넥센타이어·금호타이어가 「화학·소재 ×
    # 고무제품」으로 섰다 — 타이어는 자동차 부품이다. KSIC 가 고무제품일 때만 보므로
    # 다른 업종의 「타이어」 상호에는 걸리지 않는다
    if ksic[:4] == 'C221' and '타이어' in (name or ''):
        a, b, t, t3 = ('부품제조', '기계·운송기기', '완성차·부품', '')
        why = f'KSIC {ksic} + 이름 「타이어」'
    out.update({'A세분류': a, 'B1주업종': b, 'B1_2단': t, 'B1_3단': t3,
                'A대분류': A_대분류[a], '모수계층': 'T2', '판정근거': why})
    return out


def classify_rows(rows):
    """rows: [{'법인명','KSIC','매출액','종업원수'}, ...] → 판정 결과를 붙여 돌려준다"""
    out = []
    for r in rows:
        res = classify(r.get('KSIC'), r.get('매출액'), r.get('법인명', ''), r.get('종업원수'))
        out.append({**r, **res})
    return out


